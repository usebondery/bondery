#!/usr/bin/env node

/**
 * Replace the personal values in a real contact export with values from `base-contact-values.json`.
 *
 * Usage:
 *   node packages/tests/sample-data/anonymize.mjs vcf --input <source.vcf> --output <fixture.vcf>
 *   node packages/tests/sample-data/anonymize.mjs instagram --input <source.zip> --output <fixture.zip>
 *
 * The structure of the export is preserved line for line: the line count, the folded continuation
 * lines, the line ending, the parameter lists, the property order, and the field count of
 * structured values (`ADR`, `N`, `X-ANDROID-CUSTOM`). Only values change.
 *
 * `base-contact-values.json` is generated by `build-base-contact-values.mjs`. Run
 * `pnpm run sample-data:base` after the Bondery export sample changes.
 */
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

/**
 * Extracts a ZIP into `dir`.
 *
 * `adm-zip` resolves through this workspace package. The scripts used to shell out to `unzip`,
 * which Windows lacks, then to `tar`, which GNU tar cannot read a ZIP with on Linux CI.
 */
async function extractZip(zipPath, dir) {
  const { default: AdmZip } = await import("adm-zip");
  await mkdir(dir, { recursive: true });
  new AdmZip(zipPath).extractAllTo(dir, true);
}

/**
 * Writes the rewritten Instagram files back as one ZIP.
 *
 * Same library as the read path, so one implementation serves every platform.
 */
async function writeZip(outputPath, files) {
  const { default: AdmZip } = await import("adm-zip");
  const zip = new AdmZip();
  for (const file of files) {
    zip.addFile(file.name, file.bytes);
  }
  zip.writeZip(outputPath);
}

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BASE_DATA_PATH = path.join(HERE, "base-contact-values.json");

const LINE_BREAK = /\r?\n/u;
const CRLF = "\r\n";

/** The newline the source file uses. A CRLF file stays CRLF. An LF file stays LF. */
function sourceLineEnding(text) {
  const crlfAt = text.indexOf(CRLF);
  const lfAt = text.indexOf("\n");
  if (crlfAt !== -1 && (lfAt === -1 || crlfAt <= lfAt)) {
    return CRLF;
  }
  return "\n";
}
const BYTE_ORDER_MARK = /^\uFEFF/u;

/** The Android exporter folds at 74 octets plus the leading space, so a folded line is 75. */
const FOLD_WIDTH = 74;

