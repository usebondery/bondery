function parseArgs(argv) {
  const [mode] = argv;
  const options = {};
  for (let index = 1; index < argv.length; index += 2) {
    const key = argv[index];
    const value = argv[index + 1];
    if (!key?.startsWith("--") || value === undefined) {
      throw new Error(`Invalid argument: ${key ?? ""}`);
    }
    options[key.slice(2)] = value;
  }
  return { mode, options };
}

/** 32-bit linear congruential generator. Values stay under `Number.MAX_SAFE_INTEGER`. */
const LCG_MULTIPLIER = 1_664_525;
const LCG_INCREMENT = 1_013_904_223;
const LCG_MODULUS = 4_294_967_296;
const SEED_MULTIPLIER = 31;

function seededRandom(seedText) {
  let seed = 0;
  for (const character of seedText) {
    seed = (seed * SEED_MULTIPLIER + character.charCodeAt(0)) % LCG_MODULUS;
  }
  return () => {
    seed = (LCG_MULTIPLIER * seed + LCG_INCREMENT) % LCG_MODULUS;
    return seed / LCG_MODULUS;
  };
}

function contactFor(index, contacts, random) {
  if (contacts.length === 0) {
    throw new Error("Base contact data is empty");
  }
  if (random) {
    return contacts[Math.floor(random() * contacts.length)];
  }
  return contacts[(index - 1) % contacts.length];
}

function fullName(contact) {
  return [contact.firstName, contact.middleName, contact.lastName].filter(Boolean).join(" ");
}

/** Group labels rotate across records, so a vCard carries a label the export also uses. */
function categoryFor(index, baseData) {
  const labels = (baseData.groups ?? []).map((group) => group.label).filter(Boolean);
  if (labels.length === 0) {
    return null;
  }
  return labels[index % labels.length];
}

const QUOTED_PRINTABLE = /ENCODING=QUOTED-PRINTABLE/iu;
const UID_PREFIX = /^(?<group1>[\w.-]+-)[0-9a-fA-F-]{36}$/u;
const QUOTED_PRINTABLE_PARAM = /ENCODING=QUOTED-PRINTABLE/iu;

/**
 * Encodes a value as vCard 2.1 quoted-printable.
 *
 * A property that carries `ENCODING=QUOTED-PRINTABLE` must keep that encoding, or a reader decodes
 * plain text as escapes. Two characters must be escaped: a space becomes `=20` because a trailing
 * space would be stripped on a soft break, and `=` itself becomes `=3D`.
 */
function quotedPrintableEncode(text) {
  const bytes = Buffer.from(text, "utf8");
  let out = "";
  for (const byte of bytes) {
    const isSafeAscii = byte >= 0x21 && byte <= 0x7e && byte !== 0x3d;
    if (byte === 0x20) {
      out += "=20";
    } else if (isSafeAscii) {
      out += String.fromCharCode(byte);
    } else {
      out += `=${byte.toString(16).toUpperCase().padStart(2, "0")}`;
    }
  }
  return out;
}

/**
 * Folds a quoted-printable value into exactly `lineCount` lines at escape boundaries.
 *
 * A soft break and an escape both use `=`, so the split points must never fall inside a `=XX`
 * sequence. Every line but the last ends with `=`, which the parser strips when it unfolds.
 */
function foldQuotedPrintable(value, lineCount) {
  const tokens = [];
  for (let index = 0; index < value.length; index += 1) {
    if (value[index] === "=") {
      tokens.push(value.slice(index, index + 3));
      index += 2;
    } else {
      tokens.push(value[index]);
    }
  }
  if (lineCount <= 1) {
    return [value];
  }

  // Exactly `lineCount` lines are required. Every non-empty line but the last ends with `=`, so the
  // parser joins them. A line with no remaining tokens stays byte-empty: appending `=` there would
  // make the parser wait for a continuation that the next property cannot provide.
  const perLine = Math.max(1, Math.ceil(tokens.length / lineCount));
  const parts = [];
  let cursor = 0;
  for (let lineIndex = 0; lineIndex < lineCount; lineIndex += 1) {
    const isLast = lineIndex === lineCount - 1;
    const slice = isLast
      ? tokens.slice(cursor).join("")
      : tokens.slice(cursor, cursor + perLine).join("");
    cursor += isLast ? tokens.length - cursor : perLine;
    if (isLast) {
      parts.push(slice);
    } else if (slice.length === 0) {
      parts.push("");
    } else {
      parts.push(`${slice}=`);
    }
  }
  return parts;
}

function isContinuation(line) {
  return line.startsWith(" ") || line.startsWith("\t");
}

function splitProperty(line) {
  const colonIndex = line.indexOf(":");
  if (colonIndex < 0) {
    return null;
  }
  const lhs = line.slice(0, colonIndex);
  return { lhs, name: lhs.split(";", 1)[0].toUpperCase(), value: line.slice(colonIndex + 1) };
}

/** Repeats `text` to exactly `length` characters. */
function padToLength(text, length) {
  if (length <= 0) {
    return "";
  }
  if (text.length === 0) {
    return "x".repeat(length);
  }
  return text.repeat(Math.ceil(length / text.length)).slice(0, length);
}

/** Joins fields with `;`, keeping exactly `fieldCount` fields so the source shape survives. */
function structuredValue(fields, fieldCount) {
  const out = fields.slice(0, fieldCount);
  while (out.length < fieldCount) {
    out.push("");
  }
  return out.join(";");
}

function addressFields(contact) {
  return [
    "",
    "",
    contact.address,
    contact.city,
    contact.region,
    contact.postalCode,
    contact.country,
  ];
}

/**
 * Android writes `X-ANDROID-CUSTOM` as `mimetype;value;type;…` with up to 16 fields.
 * The mimetype names the field kind, so it stays and only the value changes.
 */
function androidCustomValue(sourceValue, index) {
  const fields = sourceValue.split(";");
  const out = [fields[0] ?? "", `sample-value-${index + 1}`];
  while (out.length < fields.length) {
    out.push(fields[out.length] ?? "");
  }
  return out.join(";");
}

/**
 * A `PHOTO` value keeps the source base64 length and stays a decodable JPEG.
 *
 * A JPEG decoder stops at the end-of-image marker, so a valid JPEG followed by filler decodes and
 * still fills the source length. The fixture then keeps the export's byte size and carries a photo
 * the importer accepts.
 */
function photoValue(sourceValue) {
  const targetLength = sourceValue.length;
  if (targetLength === 0) {
    return "";
  }
  if (SAMPLE_JPEG_BASE64.length >= targetLength) {
    return SAMPLE_JPEG_BASE64.slice(0, targetLength);
  }
  return (
    SAMPLE_JPEG_BASE64 + padToLength("SYNTHETICPHOTO", targetLength - SAMPLE_JPEG_BASE64.length)
  );
}

/** vCard properties that take a value straight from the base contact record. */
const CONTACT_VALUE_PROPERTIES = {
  BDAY: (contact) => contact.birthday,
  EMAIL: (contact) => contact.email,
  FN: (contact) => fullName(contact),
  TEL: (contact) => contact.phone,
  TITLE: (contact) => contact.title,
  URL: (contact) => contact.website,
};

/** Properties that identify the exporting application, not the person: keep them as they are. */
const KEPT_PROPERTIES = new Set(["BEGIN", "END", "PRODID", "VERSION"]);

/** Properties whose value this script generates, keyed by property name. */
const GENERATED_PROPERTIES = {
  ADR: ({ contact, fieldCount }) => structuredValue(addressFields(contact), fieldCount),
  CATEGORIES: ({ baseData, index }) => categoryFor(index, baseData) ?? "",
  // vCard `N` is `family;given;additional;prefix;suffix`. A leading empty field would shift the
  // family name into the prefix slot and misname every contact.
  N: ({ contact, fieldCount }) =>
    structuredValue(
      [contact.lastName ?? "", contact.firstName ?? "", contact.middleName ?? "", "", ""],
      fieldCount,
    ),
  NOTE: ({ index }) => `Synthetic contact note ${index + 1}`,
  // `ORG:Name;` is two fields and `ORG:Name` is one, so the source field count decides.
  ORG: ({ contact, fieldCount }) => structuredValue([contact.organization ?? ""], fieldCount),
  PHOTO: ({ sourceValue }) => photoValue(sourceValue),
  UID: ({ index, sourceValue }) => syntheticUid(sourceValue, index),
  "X-ANDROID-CUSTOM": ({ index, sourceValue }) => androidCustomValue(sourceValue, index),
  "X-SAMSUNGADR": ({ contact, fieldCount }) => structuredValue(addressFields(contact), fieldCount),
};

/**
 * Returns the replacement value for one property, or `null` to keep the line exactly as it is.
 * An empty result is valid: the property stays, an unknown value becomes empty.
 */
function substituteValue({ baseData, contact, index, name, sourceValue }) {
  const fieldCount = sourceValue.split(";").length;

  if (KEPT_PROPERTIES.has(name)) {
    return null;
  }

  const generator = GENERATED_PROPERTIES[name];
  if (generator !== undefined) {
    return generator({ baseData, contact, fieldCount, index, sourceValue });
  }

  const readContactField = CONTACT_VALUE_PROPERTIES[name.split(".").at(-1)];
  if (readContactField !== undefined) {
    return readContactField(contact) ?? "";
  }

  // An unknown property keeps its shape and loses its value.
  return structuredValue([`sample-value-${index + 1}`], fieldCount);
}

/**
 * A `UID` identifies one exported record, so the source value is an account-level identifier.
 * The prefix and the identifier format stay, the identifier becomes synthetic and stable per
 * record, so a re-run produces the same fixture.
 */
function syntheticUid(sourceValue, index) {
  const serial = String(index + 1).padStart(12, "0");
  const uuid = `00000000-0000-4000-8000-${serial}`;
  if (sourceValue.startsWith("urn:uuid:")) {
    return `urn:uuid:${uuid}`;
  }
  // `proton-autosave-<uuid>` and any other `prefix-<uuid>` form keep their prefix.
  const prefixMatch = UID_PREFIX.exec(sourceValue);
  if (prefixMatch?.[1] !== undefined) {
    return `${prefixMatch[1]}${uuid}`;
  }
  return sourceValue === "" ? "" : `urn:uuid:${uuid}`;
}

/**
 * Folds `value` into exactly `lineCount` lines, using the source's fold convention.
 *
 * Three conventions appear in real exports and each must survive: a space continuation (RFC 6350),
 * a quoted-printable soft break (vCard 2.1, trailing `=`), and no folding at all.
 */
function foldValue(value, lineCount, sourceFoldLengths, options) {
  if (lineCount <= 1) {
    return [value];
  }

  if (options.keepSourceLengths) {
    const parts = [];
    let cursor = 0;
    for (let lineIndex = 0; lineIndex < lineCount; lineIndex += 1) {
      const payload =
        lineIndex === 0 ? sourceFoldLengths[0] : Math.max(sourceFoldLengths[lineIndex] - 1, 0);
      const chunk = value.slice(cursor, cursor + payload);
      parts.push(lineIndex === 0 ? chunk : ` ${chunk}`);
      cursor += chunk.length;
    }
    return parts;
  }

  const continuationWidth = FOLD_WIDTH - 1;
  const parts = [];
  let cursor = 0;
  for (let lineIndex = 0; lineIndex < lineCount; lineIndex += 1) {
    const remaining = value.length - cursor;
    const remainingLines = lineCount - lineIndex;
    const size = Math.min(continuationWidth, Math.ceil(remaining / remainingLines));
    const chunk = value.slice(cursor, cursor + Math.max(size, 0));
    parts.push(lineIndex === 0 ? chunk : ` ${chunk}`);
    cursor += chunk.length;
  }
  return parts;
}

/** One logical property: a start line plus the continuation lines that belong to it. */
function readLogicalProperties(lines) {
  const properties = [];
  let current = null;
  for (const line of lines) {
    if (current !== null && isContinuation(line)) {
      current.continuations.push(line);
      current.logical += line.slice(1);
      continue;
    }
    // A quoted-printable soft break continues the property before it, without a leading space.
    // The parser tests the joined logical line, so a three-line chain keeps matching.
    if (current?.logical.endsWith("=") === true && QUOTED_PRINTABLE.test(current.logical)) {
      current.continuations.push(line);
      current.logical = `${current.logical.slice(0, -1)}${line}`;
      continue;
    }
    current = { continuations: [], line, logical: line };
    properties.push(current);
  }
  return properties;
}

/** The property value, unfolded the way the parser unfolds it. */
function joinedValue(property) {
  return property.logical.slice(property.logical.indexOf(":") + 1);
}

function anonymizeVCardBlock({ baseData, block, index, lineEnding, random }) {
  const contact = contactFor(index + 1, baseData.contacts, () => random());
  const lines = [];

  for (const property of readLogicalProperties(block.split(LINE_BREAK))) {
    const parsed = splitProperty(property.line);
    if (parsed === null) {
      lines.push(property.line, ...property.continuations);
      continue;
    }

    const value = substituteValue({
      baseData,
      contact,
      index,
      name: parsed.name,
      sourceValue: joinedValue(property),
    });

    if (value === null) {
      lines.push(property.line, ...property.continuations);
      continue;
    }

    const sourceFoldLengths = [
      property.line.length - parsed.lhs.length - 1,
      ...property.continuations.map((part) => part.length),
    ];
    // A quoted-printable property needs a quoted-printable value, or a reader decodes plain text.
    const quotedPrintable = QUOTED_PRINTABLE_PARAM.test(parsed.lhs);
    let folded;
    if (quotedPrintable) {
      folded = foldQuotedPrintable(quotedPrintableEncode(value), property.continuations.length + 1);
    } else {
      folded = foldValue(value, property.continuations.length + 1, sourceFoldLengths, {
        keepSourceLengths: parsed.name === "PHOTO",
      });
    }
    lines.push(
      ...folded.map((part, partIndex) => (partIndex === 0 ? `${parsed.lhs}:${part}` : part)),
    );
  }

  return lines.join(lineEnding);
}

async function anonymizeVcf(inputPath, outputPath, baseData) {
  const text = await readFile(inputPath, "utf8");
  const blocks = text.match(/BEGIN:VCARD[\s\S]*?END:VCARD/giu) ?? [];
  if (blocks.length === 0) {
    throw new Error("No vCard records found");
  }

  const random = seededRandom(`${inputPath}:${outputPath}`);
  const lineEnding = sourceLineEnding(text);
  const outputBlocks = blocks.map((block, index) =>
    anonymizeVCardBlock({ baseData, block, index, lineEnding, random }),
  );

  // Some exporters end the last record without a newline. Keep that ending, and keep LF when
  // the source is LF. A forced CRLF changes the line count the structure check compares.
  const trailingNewline = text.endsWith(lineEnding) ? lineEnding : "";
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${outputBlocks.join(lineEnding)}${trailingNewline}`, "utf8");
  console.log(`Anonymized ${outputBlocks.length} vCards to ${outputPath}`);
}

function syntheticTimestamp(index) {
  return 1_700_000_000 + index;
}

/**
 * Substitutes one string field. A `value` field takes its meaning from the sibling `label`.
 *
 * Two source conventions are kept because consumers depend on them:
 * - An empty source value stays empty. Instagram leaves `title` empty in `followers_*.json` and
 *   `URL` empty in `close_friends.json`, and a filled-in value would hide that case from a test.
 * - A profile URL keeps its path prefix. Recent exports write `…/instagram.com/_u/<handle>`, and
 *   the importer must handle that form.
 */
function substituteStringValue({ contact, key, label, value }) {
  // An empty source value stays empty: Instagram omits `URL` and `title` in some records, and a
  // filled-in value would hide that case from a test.
  if (value === "") {
    return "";
  }
  const isUrlKey = key === "href" || key === "url" || (key === "value" && label === "url");
  if (isUrlKey) {
    const suffix = value.includes("/_u/") ? `_u/${contact.instagram}` : contact.instagram;
    return `https://www.instagram.com/${suffix}`;
  }
  if (key === "name" || (key === "value" && label === "name")) {
    return fullName(contact);
  }
  if (key === "value") {
    return contact.instagram;
  }
  if (IDENTITY_KEYS.has(key)) {
    return contact.instagram;
  }
  return value;
}

/**
 * Rewrites one relationship record against a single contact.
 *
 * A record names the same person up to four times: `title`, `string_list_data[].value`,
 * `string_list_data[].href`, and the `Name`/`Username`/`URL` entries of `label_values`. Every
 * occurrence takes the same substitute, so a fixture never claims one handle in `title` and a
 * different one in `href`.
 */
function rewriteRecord(value, contact, state) {
  if (Array.isArray(value)) {
    return value.map((item) => rewriteRecord(item, contact, state));
  }
  if (!value || typeof value !== "object") {
    return value;
  }

  const label = typeof value.label === "string" ? value.label.toLowerCase() : null;

  for (const [rawKey, child] of Object.entries(value)) {
    const key = rawKey.toLowerCase();

    if (key === "timestamp" && typeof child === "number") {
      state.timestampIndex += 1;
      value[rawKey] = syntheticTimestamp(state.timestampIndex);
    } else if (typeof child === "string") {
      value[rawKey] = substituteStringValue({ contact, key, label, value: child });
    } else {
      value[rawKey] = rewriteRecord(child, contact, state);
    }
  }

  return value;
}

/** Instagram wraps some arrays in an object (`{ "relationships_following": [...] }`). */
function relationshipArrays(payload) {
  if (Array.isArray(payload)) {
    return [{ owner: null, records: payload }];
  }
  if (!payload || typeof payload !== "object") {
    return [];
  }
  return Object.entries(payload)
    .filter(([, child]) => Array.isArray(child))
    .map(([owner, records]) => ({ owner, records }));
}

/** One contact per record, in file order, so the corpus stays stable across runs. */
function anonymizeInstagramPayload(payload, baseData, state) {
  for (const { owner, records } of relationshipArrays(payload)) {
    const rewritten = records.map((record) => {
      state.recordIndex += 1;
      const contact = contactFor(state.recordIndex, baseData.contacts);
      return rewriteRecord(record, contact, state);
    });
    if (owner === null) {
      return rewritten;
    }
    payload[owner] = rewritten;
  }
  return payload;
}

async function readInstagramEntry(entry, sourceDir) {
  const sourcePath = path.join(entry.parentPath, entry.name);
  const relativeName = path.relative(sourceDir, sourcePath);
  if (!entry.name.toLowerCase().endsWith(".json")) {
    return { bytes: await readFile(sourcePath), name: relativeName, payload: null };
  }
  const text = (await readFile(sourcePath, "utf8")).replace(BYTE_ORDER_MARK, "");
  try {
    return { bytes: null, name: relativeName, payload: JSON.parse(text) };
  } catch (error) {
    throw new Error(`Could not parse Instagram JSON file ${relativeName}`, { cause: error });
  }
}

async function anonymizeInstagram(inputPath, outputPath, baseData) {
  const workDir = await mkdtemp(path.join(tmpdir(), "bondery-instagram-anonymize-"));
  const sourceDir = path.join(workDir, "source");
  const outputDir = path.join(workDir, "output");
  const state = { recordIndex: 0, timestampIndex: 0 };

  try {
    await mkdir(sourceDir, { recursive: true });
    await mkdir(outputDir, { recursive: true });
    await extractZip(inputPath, sourceDir);
    const entries = await readdir(sourceDir, { recursive: true, withFileTypes: true });
    const files = entries.filter((entry) => entry.isFile());
    if (files.length === 0) {
      throw new Error(`No files found in ${inputPath}`);
    }

    const read = await Promise.all(files.map((entry) => readInstagramEntry(entry, sourceDir)));
    const written = read.map((file) => {
      const payload =
        file.payload === null ? null : anonymizeInstagramPayload(file.payload, baseData, state);
      return {
        bytes: payload === null ? file.bytes : Buffer.from(`${JSON.stringify(payload, null, 2)}\n`),
        name: file.name,
      };
    });

    await Promise.all(
      written.map(async (file) => {
        const targetPath = path.join(outputDir, file.name);
        await mkdir(path.dirname(targetPath), { recursive: true });
        await writeFile(targetPath, file.bytes);
      }),
    );

    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeZip(outputPath, written);
    console.log(`Anonymized ${written.length} Instagram export files to ${outputPath}`);
  } finally {
    await rm(workDir, { force: true, recursive: true });
  }
}

async function main() {
  const { mode, options } = parseArgs(process.argv.slice(2));
  if (!mode || mode === "help" || mode === "--help" || !options.input || !options.output) {
    usage();
    if (!mode) {
      process.exitCode = 1;
    }
    return;
  }

  const baseData = JSON.parse(await readFile(BASE_DATA_PATH, "utf8"));
  if (mode === "vcf") {
    await anonymizeVcf(options.input, options.output, baseData);
  } else if (mode === "instagram") {
    await anonymizeInstagram(options.input, options.output, baseData);
  } else {
    throw new Error(`Unknown mode: ${mode}`);
  }
}

await main();
