import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Renders each product mark to an inline SVG data URI.
 *
 * `src/assets/brands/*.svg` stay the single source of truth. These marks render as CSS masks on a
 * brand-coloured tile, so only the glyph outline matters: the SVG is kept as vector and never
 * rasterised, which keeps every logo crisp on any display.
 *
 * A data URI avoids a file request per tile, and keeps the marks working from a package `dist`
 * folder where the bundler cannot resolve a URL relative to the module.
 */
const __dirname = dirname(fileURLToPath(import.meta.url));
const ASSETS_DIR = join(__dirname, "../src/assets/brands");
const OUT_FILE = join(__dirname, "../src/brandIcons.generated.ts");

/**
 * Product marks shown on a brand-coloured tile.
 *
 * `background` is the official brand colour, or the brand gradient where the mark has one.
 * `Simple Icons` dropped LinkedIn for trademark reasons, so that file is authored here.
 */
const MARKS: ReadonlyArray<{ background: string; name: string; svg: string }> = [
  { background: "#0A66C2", name: "linkedin", svg: "linkedin.svg" },
  {
    background:
      "linear-gradient(45deg, #f09433 0%, #e6683c 25%, #dc2743 50%, #cc2366 75%, #bc1888 100%)",
    name: "instagram",
    svg: "instagram.svg",
  },
  { background: "#181717", name: "github", svg: "github.svg" },
  { background: "#2F2F2F", name: "modelcontextprotocol", svg: "modelcontextprotocol.svg" },
  { background: "#4285F4", name: "chromewebstore", svg: "chromewebstore.svg" },
];

/**
 * Percent-encodes an SVG for a data URI.
 *
 * Only the characters that break a CSS `url()` are escaped, so the payload stays readable and
 * small. A `#` in a colour would otherwise start a fragment and truncate the image.
 */
function encodeSvg(svg: string): string {
  const minified = svg
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();

  const escaped = minified
    .replace(/%/g, "%25")
    .replace(/"/g, "'")
    .replace(/#/g, "%23")
    .replace(/\n/g, " ");

  return `data:image/svg+xml;utf8,${escaped}`;
}

const names = MARKS.map((mark) => `"${mark.name}"`).join(" | ");

const srcEntries = MARKS.map((mark) => {
  const svg = readFileSync(join(ASSETS_DIR, mark.svg), "utf8");
  return `  ${mark.name}: "${encodeSvg(svg)}",`;
}).join("\n");

const backgroundEntries = MARKS.map((mark) => `  ${mark.name}: "${mark.background}",`).join("\n");

const contents = `/**
 * Product marks rendered as CSS masks on a brand-coloured tile.
 *
 * Generated by \`pnpm run generate:brand-icons\` in \`@bondery/branding\`.
 * Do not edit by hand. \`src/assets/brands/*.svg\` are the sources.
 *
 * Each source is a single-colour glyph. Size it with \`width\` and \`height\`, and paint the glyph
 * with \`background-color\` plus a \`mask-image\` built from these values.
 */
export type BrandIconName = ${names};

/** The glyph outline, as an inline SVG data URI. Use it as a CSS \`mask-image\`. */
export const BRAND_ICON_SRC: Record<BrandIconName, string> = {
${srcEntries}
};

/** Official brand background: a colour, or the brand gradient where the mark has one. */
export const BRAND_ICON_BACKGROUND: Record<BrandIconName, string> = {
${backgroundEntries}
};
`;

writeFileSync(OUT_FILE, contents);
console.log(`Wrote ${OUT_FILE}`);
