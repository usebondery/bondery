import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/**
 * Renders each brand mark to a PNG data URI for icon-size use.
 *
 * `src/assets/brands/*.svg` stay the single source of truth. `linux.svg` is a
 * detailed illustration of about 190 kB, so inlining it for a 14 px icon would
 * cost far more than the artwork it draws. A 3x PNG of the same artwork is a
 * few kilobytes and stays crisp on current displays.
 */
const __dirname = dirname(fileURLToPath(import.meta.url));
const ASSETS_DIR = join(__dirname, "../src/assets/brands");
const OUT_FILE = join(__dirname, "../src/brandMarks.generated.ts");

/** CSS px of the rendered mark. 3x covers retina and 3x phone displays. */
const MARK_SIZE_PX = 42;

/** Marks that read on both themes, so one file is enough. */
const MARKS = ["windows", "apple", "linux", "javascript", "python"];

/**
 * Marks with a light-theme file and an inverse file for the dark theme.
 *
 * Both `curl` logo variants are a single flat fill. The brand navy is unreadable
 * on a dark surface, so the dark theme swaps in the white file.
 */
const THEMED_MARKS: ReadonlyArray<{ dark: string; light: string; name: string }> = [
  { dark: "curl-inverse", light: "curl", name: "curl" },
];

/** Renders one brand SVG to an inline PNG data URI. */
async function dataUri(file: string): Promise<string> {
  const png = await sharp(join(ASSETS_DIR, `${file}.svg`))
    .resize(MARK_SIZE_PX, MARK_SIZE_PX, {
      background: { alpha: 0, b: 0, g: 0, r: 0 },
      fit: "contain",
    })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();

  return `data:image/png;base64,${png.toString("base64")}`;
}

const entries: string[] = [];
for (const name of MARKS) {
  entries.push(`  ${name}: "${await dataUri(name)}",`);
}

const themedEntries: string[] = [];
for (const mark of THEMED_MARKS) {
  themedEntries.push(
    [
      `  ${mark.name}: {`,
      `    dark: "${await dataUri(mark.dark)}",`,
      `    light: "${await dataUri(mark.light)}",`,
      "  },",
    ].join("\n"),
  );
}

const markNames = [...MARKS, ...THEMED_MARKS.map((mark) => mark.name)];

const contents = `/**
 * Brand platform and language marks, generated by \`pnpm run generate:brand-marks\` in \`@bondery/branding\`.
 *
 * Do not edit by hand. \`src/assets/brands/*.svg\` are the sources.
 * A PNG at ${MARK_SIZE_PX}px keeps \`linux\` at a few kilobytes, where its source SVG is ~190 kB.
 * Language logos come from dashboardicons.com, which serves the selfh.st and Simple Icons catalogs.
 */
export type BrandMarkName = ${markNames.map((name) => `"${name}"`).join(" | ")};

/** A mark with one file per theme, for artwork that does not read on both surfaces. */
export type ThemedBrandMarkName = ${THEMED_MARKS.map((mark) => `"${mark.name}"`).join(" | ")};

export const BRAND_MARKS: Record<Exclude<BrandMarkName, ThemedBrandMarkName>, string> = {
${entries.join("\n")}
};

export const THEMED_BRAND_MARKS: Record<ThemedBrandMarkName, { dark: string; light: string }> = {
${themedEntries.join("\n")}
};
`;

writeFileSync(OUT_FILE, contents);
console.log(`Wrote ${OUT_FILE}`);
