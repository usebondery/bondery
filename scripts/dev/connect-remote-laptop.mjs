/**
 * Point a laptop browser at this PC's dev stack over Tailscale.
 *
 * Run this on the PC. It writes a PowerShell script that the laptop runs once.
 *
 * Why this exists: a remote Orca session renders its browser pane on the laptop, not on
 * this machine. Portless binds `127.0.0.1:443` here, so the laptop cannot reach it by
 * loopback. Two bridges work:
 *
 * 1. SSH tunnel — `scripts/dev/connect-remote-portless.ps1`. Needs an SSH server here.
 * 2. This device's Tailscale name — needs no server, and works today.
 *
 * The Portless CA is trusted on this machine after `pnpm exec portless trust`, which never
 * reaches the laptop. The laptop needs the CA in its own Windows root store. That is why a
 * browser warns even when `curl` on this machine succeeds.
 *
 * The laptop maps the `.test` hostnames to this machine's Tailscale address. Its hosts file
 * needs a literal address, not a MagicDNS name, because the laptop may not resolve MagicDNS.
 *
 * Usage:
 *   pnpm run dev:remote-laptop
 *   BONDERY_DEV_TAILSCALE_HOST=<machine>.<tailnet>.ts.net pnpm run dev:remote-laptop
 */
import { spawnSync } from "node:child_process";
import { X509Certificate } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { DEV_URLS } from "@bondery/schemas/constants/dev-ports";

import { missingTailscaleHostMessage, resolveTailscaleDeviceUrl } from "./tailscale-host.mjs";

const HTTPS_PREFIX = "https://";
const TLD = "test";
const PORTLESS_PROXY_PORT = 443;
const IPV4_RE = /^\d{1,3}(?<group1>\.\d{1,3}){3}$/u;

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const OUTPUT_PATH = join(repoRoot, ".temp/connect-laptop.ps1");

/**
 * Hostnames Portless serves on HTTPS. Mirrors `portlessHttpsHostnames` in
 * `connect-remote-portless.mjs`, so the two laptop paths cannot disagree.
 *
 * @param {typeof DEV_URLS} urls
 * @returns {string[]}
 */
function portlessHttpsHostnames(urls = DEV_URLS) {
  const names = new Set();
  for (const value of Object.values(urls)) {
    if (typeof value !== "string" || !value.startsWith(HTTPS_PREFIX)) {
      continue;
    }
    const { hostname } = new URL(value);
    if (hostname.endsWith(`.${TLD}`)) {
      names.add(hostname);
    }
  }
  return [...names].sort((a, b) => Number(a > b) - Number(a < b));
}

/**
 * The host to open first: the website, which serves a page at `/`. The API answers 404 on `/`.
 *
 * @param {string[]} hostnames
 * @returns {string}
 */
function primaryHost(hostnames) {
  const website = new URL(DEV_URLS.website).hostname;
  return hostnames.includes(website) ? website : (hostnames[0] ?? "usebondery.test");
}

/**
 * This machine's Tailscale IPv4 address. The laptop hosts file needs a literal address.
 *
 * @returns {string | undefined}
 */
function tailscaleAddress() {
  const result = spawnSync("tailscale", ["ip", "-4"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  if (result.status !== 0) {
    return;
  }
  const first = result.stdout.split("\n")[0].trim();
  return IPV4_RE.test(first) ? first : undefined;
}

/**
 * A complete, dependency-free PowerShell script for the laptop.
 *
 * The CA is pinned to the SHA-256 of the certificate this PC serves, so the laptop refuses
 * a substituted certificate instead of trusting whatever it downloaded.
 *
 * @param {{{ address: string, caPem: string, caSha256: string, hostnames: string[] }} input
 * @returns {string}
 */
function buildLaptopScript({ address, caPem, caSha256, hostnames, openHost }) {
  const hostsValues = hostnames.map((hostname) => `${address} ${hostname}`);

  // PowerShell here-strings need their terminator at column zero. Template placeholders are
  // built first so nothing above them can indent it.
  const hostsArray = hostsValues.map((line) => `  "${line}"`).join("\n");

  return `# Point this laptop at the Bondery dev stack on the PC, over Tailscale.
#
# Generated by \`pnpm run dev:remote-laptop\` on the PC. Run it in an ELEVATED PowerShell.
#
# Writes one hosts block and trusts the Portless CA for your Windows user. Installs nothing
# else. Remove the hosts block later by deleting the lines between the BONDERY-REMOTE-PORTLESS
# markers in C:\\Windows\\System32\\drivers\\etc\\hosts.

$ErrorActionPreference = "Stop"

$hostsPath = Join-Path $env:SystemRoot "System32\\drivers\\etc\\hosts"
$markerBegin = "# BEGIN BONDERY-REMOTE-PORTLESS"
$markerEnd = "# END BONDERY-REMOTE-PORTLESS"

# --- 1. Hosts: point the .test names at the PC over Tailscale ---
$content = [System.IO.File]::ReadAllText($hostsPath)
$pattern = "(?ms)^" + [regex]::Escape($markerBegin) + ".*?^" + [regex]::Escape($markerEnd) + "\\r?\\n?"
$content = [regex]::Replace($content, $pattern, "").TrimEnd()
$block = @(
  $markerBegin
${hostsArray}
  $markerEnd
) -join "\`r\`n"
[System.IO.File]::WriteAllText($hostsPath, $content + "\`r\`n\`r\`n" + $block + "\`r\`n")
Write-Host "Wrote ${hostnames.length} hostname(s) to $hostsPath"

# --- 2. Trust the Portless CA for your Windows user ---
$caPath = Join-Path $env:TEMP "bondery-portless-ca.pem"
$caPem = @'
${caPem.trim()}
'@
Set-Content -Path $caPath -Value $caPem -Encoding ascii

$cert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2 $caPath
$expected = "${caSha256}"
$actual = $cert.GetCertHashString("SHA256")
if ($actual -ne $expected) {
  throw "CA fingerprint mismatch. Expected $expected, found $actual. Not trusting this certificate."
}

$alreadyTrusted = Get-ChildItem Cert:\\CurrentUser\\Root | Where-Object { $_.Thumbprint -eq $cert.Thumbprint }
if ($alreadyTrusted) {
  Write-Host "Portless CA already trusted for this user."
} else {
  certutil.exe -user -addstore Root $caPath | Out-Host
  if ($LASTEXITCODE -ne 0) { throw "certutil failed to trust the Portless CA." }
  Write-Host "Trusted the Portless CA for this Windows user."
}

Write-Host ""
Write-Host "Done. Fully quit and reopen Orca, so its browser pane re-reads the root store."
Write-Host "Then open: https://${openHost}/"
`;
}

/**
 * Checks to run before handing over the script. Each names the command that fixes it.
 *
 * @param {string[]} hostnames
 * @returns {string[]}
 */
function preflightNotes(hostnames) {
  return [
    `Portless must own TCP ${PORTLESS_PROXY_PORT} on this PC: ss -ltnp | grep ":${PORTLESS_PROXY_PORT}\\b"`,
    "The apps must be running (`pnpm run dev`); the proxy returns 502 when they are not.",
    `Hostnames that will be mapped: ${hostnames.join(", ")}`,
  ];
}

function main() {
  const hostnames = portlessHttpsHostnames();
  const device = resolveTailscaleDeviceUrl();

  if (!device) {
    console.error(missingTailscaleHostMessage(hostnames));
    process.exitCode = 1;
    return;
  }

  const address = tailscaleAddress();
  if (!address) {
    console.error(
      "Could not read this PC's Tailscale address. Run `tailscale up`, then check:\n  tailscale ip -4",
    );
    process.exitCode = 1;
    return;
  }

  const caPath = join(homedir(), ".portless/ca.pem");
  let caPem;
  try {
    caPem = readFileSync(caPath, "utf-8");
  } catch {
    console.error(
      `Could not read ${caPath}. Start Portless first so it creates the CA:\n  pnpm run dev`,
    );
    process.exitCode = 1;
    return;
  }

  const caSha256 = new X509Certificate(caPem).fingerprint256.replaceAll(":", "");

  const script = buildLaptopScript({
    address,
    caPem,
    caSha256,
    hostnames,
    openHost: primaryHost(hostnames),
  });
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, script, "utf-8");

  console.log("A remote Orca session renders its browser pane on the laptop, so the laptop");
  console.log("needs the hosts entry and the Portless CA. This PC already has both.");
  console.log("");
  console.log(`Tailscale name : ${device.url.replace(HTTPS_PREFIX, "")}  (from ${device.source})`);
  console.log(`Address        : ${address}`);
  console.log(`CA             : ${caPath}`);
  console.log(`CA SHA-256     : ${caSha256}`);
  console.log("");
  console.log(`Wrote a ready-to-run script: ${OUTPUT_PATH}`);
  console.log("");
  console.log("Copy that file to the laptop, then in an ELEVATED PowerShell:");
  console.log("  .\\connect-laptop.ps1");
  console.log("");
  console.log(`Then fully quit and reopen Orca, and open https://${primaryHost(hostnames)}/`);
  console.log("");
  console.log("Before you start, confirm on this PC:");
  for (const note of preflightNotes(hostnames)) {
    console.log(`  - ${note}`);
  }
}

main();
