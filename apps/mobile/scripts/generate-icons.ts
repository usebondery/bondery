import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateIcons } from "@bondery/branding/icon-generator";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const icons = [
  {
    format: "png" as const,
    name: "icon_512.png",
    outDir: "../assets/images",
    size: 512,
  },
  {
    format: "png" as const,
    name: "icon_1024.png",
    outDir: "../assets/images",
    size: 1024,
  },
  {
    format: "png" as const,
    name: "splash-icon.png",
    outDir: "../assets/images",
    size: 512,
  },
  {
    format: "svg" as const,
    name: "icon.svg",
    outDir: "../assets/images",
  },
];

const svgPath = join(__dirname, "../../../packages/branding/src/assets/icon.svg");
const svgModulePath = join(__dirname, "../src/features/auth/bonderyMarkSvg.generated.ts");

function writeIconSvgModule(svgContents: string): void {
  const normalized = svgContents.replace(/\r\n/g, "\n");
  const next = `// Generated by scripts/generate-icons.ts — do not edit.\nexport const BONDERY_ICON_SVG = ${JSON.stringify(normalized)};\n`;
  if (existsSync(svgModulePath) && readFileSync(svgModulePath, "utf8") === next) {
    return;
  }
  writeFileSync(svgModulePath, next);
}

async function main(): Promise<void> {
  await generateIcons({
    baseDir: __dirname,
    icons,
    svgPath,
  });
  writeIconSvgModule(readFileSync(svgPath, "utf8"));
}

void main().catch((error: unknown) => {
  console.error("❌ Error writing login SVG module:", error);
  process.exit(1);
});
