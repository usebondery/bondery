/**
 * Generates `src/components/landing/features/globe-data.ts`: land dots for the dotted globe
 * on the "Find anyone" tile, projected orthographically, plus the projected position of each
 * city a contact pin sits on.
 *
 * The output is committed, so the site needs none of these packages. Run it only to change
 * the rotation, dot density, or cities. The data packages are not website dependencies, so
 * install them in a scratch folder and pass that folder as the first argument:
 *
 *   mkdir /tmp/globe-gen && cd /tmp/globe-gen && npm init -y
 *   npm install d3-geo@3 topojson-client@3 world-atlas@2
 *   node apps/website/scripts/generate-globe-dots.mjs /tmp/globe-gen
 *
 * Land comes from Natural Earth via `world-atlas` (public domain).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const depsDir = process.argv[2];
if (!depsDir) {
  throw new Error(
    "Pass the folder where d3-geo, topojson-client, and world-atlas are installed as the first argument.",
  );
}

const requireFrom = createRequire(path.join(path.resolve(depsDir), "noop.js"));
const { geoContains } = requireFrom("d3-geo");
const { feature } = requireFrom("topojson-client");
const topology = JSON.parse(
  readFileSync(requireFrom.resolve("world-atlas/land-110m.json"), "utf-8"),
);
const land = feature(topology, topology.objects.land);

/** Globe centre (degrees). Europe and Africa face the viewer. */
const CENTER_LON = 14;
const CENTER_LAT = 28;
/** Spacing between dots, in degrees of latitude. */
const STEP = 2.6;
/** Globe radius in the 100 unit SVG box, centred at 50, 50. */
const RADIUS = 46;

const toRad = (deg) => (deg * Math.PI) / 180;
const round = (value, places = 1) => Number(value.toFixed(places));

/** Orthographic projection. Returns null when the point is on the far side. */
function project(lon, lat) {
  const phi = toRad(lat);
  const phi0 = toRad(CENTER_LAT);
  const dLon = toRad(lon - CENTER_LON);
  const cosC = Math.sin(phi0) * Math.sin(phi) + Math.cos(phi0) * Math.cos(phi) * Math.cos(dLon);
  if (cosC <= 0.03) {
    return null;
  }
  const x = Math.cos(phi) * Math.sin(dLon);
  const y = Math.cos(phi0) * Math.sin(phi) - Math.sin(phi0) * Math.cos(phi) * Math.cos(dLon);
  return { cosC, x: 50 + RADIUS * x, y: 50 - RADIUS * y };
}

const dots = [];
for (let lat = -80; lat <= 84; lat += STEP) {
  // Fewer dots per row toward the poles keeps the spacing even on the sphere.
  const count = Math.max(1, Math.round((360 * Math.cos(toRad(lat))) / STEP));
  for (let i = 0; i < count; i += 1) {
    const lon = -180 + (360 * (i + 0.5)) / count;
    if (!geoContains(land, [lon, lat])) {
      continue;
    }
    const p = project(lon, lat);
    if (p) {
      // Dots shrink toward the edge, which reads as curvature without any shading.
      dots.push([round(p.x), round(p.y), round(0.42 + 0.4 * p.cosC, 2)]);
    }
  }
}

/** Cities the contact pins sit on: [name, lon, lat]. */
const CITIES = [
  ["london", -0.13, 51.51],
  ["cairo", 31.24, 30.04],
  ["lagos", 3.38, 6.52],
  ["nairobi", 36.82, -1.29],
  ["mumbai", 72.88, 19.08],
];

const cities = Object.fromEntries(
  CITIES.map(([name, lon, lat]) => {
    const p = project(lon, lat);
    if (!p) {
      throw new Error(`${name} is on the far side of the globe.`);
    }
    return [name, [round(p.x), round(p.y)]];
  }),
);

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../src/components/landing/features/globe-data.ts");

const body = `// biome-ignore-all lint/style/noExcessiveLinesPerFile: generated data
// biome-ignore-all format: generated data
// Generated by apps/website/scripts/generate-globe-dots.mjs. Do not edit by hand.
// Orthographic projection centred on ${CENTER_LAT}N ${CENTER_LON}E in a 100 x 100 box.
// Land: Natural Earth via world-atlas (public domain).

/** Land dots as [x, y, radius]. */
export const GLOBE_DOTS: ReadonlyArray<readonly [number, number, number]> = ${JSON.stringify(dots)};

/** Pin positions as [x, y] in the same box. */
export const GLOBE_CITIES = ${JSON.stringify(cities)} as const;

export const GLOBE_RADIUS = ${RADIUS};
`;

writeFileSync(out, body);
console.log(
  `${dots.length} dots, ${Object.keys(cities).length} cities -> ${path.relative(process.cwd(), out)}`,
);
console.log(cities);
